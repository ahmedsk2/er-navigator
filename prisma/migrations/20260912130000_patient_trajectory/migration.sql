-- Phase 15 (docs/specs/phase15-trajectory.md, item 1): the patient trajectory Ahmed asked for on
-- 12 September, so the Patient journey block can show the steps a pathway has and hide the ones
-- it cannot before the outcome is known.
--
--   * Trajectory — a vocabulary of three: DISCHARGE, ADMISSION, TRANSFER. An addition, like the
--     Phase 8b answers and the Phase 10 payers; no Disposition value is renamed or removed.
--   * Case.trajectory — nullable and without a default. NULL is "not decided yet", which every
--     case carries until somebody taps a chip, and which the two outcomes that are none of the
--     three (left without being seen, deceased) may never leave. Never required, at "Open case"
--     or at "Mark resolved", and never inferred from the disposition.
--
-- Every existing row is untouched and nothing is backfilled: the same shape the Phase 8, Phase 10
-- and Phase 14 collection columns took.
--
-- No GRANT here. ALTER DEFAULT PRIVILEGES (20260908190100) covers new tables and
-- prisma/sync-app-role.ts re-applies the app role's grants on every deploy, so a new column on an
-- existing table needs neither; and a Postgres enum type carries USAGE for PUBLIC unless it is
-- revoked, which this schema never does. Generated by `prisma migrate diff
-- --from-config-datasource --to-schema prisma/schema.prisma --script` against the migrated lead
-- database and read line by line, because the shadow database `prisma migrate dev` needs does not
-- work in this repository (docs/RUNBOOK.md).

-- CreateEnum
CREATE TYPE "Trajectory" AS ENUM ('DISCHARGE', 'ADMISSION', 'TRANSFER');

-- AlterTable
ALTER TABLE "Case" ADD COLUMN     "trajectory" "Trajectory";
