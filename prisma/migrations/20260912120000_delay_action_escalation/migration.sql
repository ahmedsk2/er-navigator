-- prisma/sync-app-role.ts re-applies the app role's grants on every deploy; a new column on an
-- existing table needs neither. Generated by `prisma migrate diff --from-config-datasource
-- --to-schema prisma/schema.prisma --script` against the migrated lead database and read line by
-- line, because the shadow database `prisma migrate dev` needs does not work in this repository
-- (docs/RUNBOOK.md).
